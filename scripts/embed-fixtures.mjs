// Generates db/903_bench_embeddings.sql: embeddings for the 50 products and 50 queries.
// Uses the Hugging Face Inference API with intfloat/multilingual-e5-small (384 numbers).
//
// Run on your own machine (Node 20 or newer), with a Hugging Face token in .env:
//   HF_TOKEN=hf_...
//   node --env-file=.env scripts/embed-fixtures.mjs
//
// For SQL testing without a token: --fake writes deterministic made-up vectors.
//   node scripts/embed-fixtures.mjs --fake --out /tmp/903_fake.sql
//
// Note: written in a cloud session that cannot reach Hugging Face, so the API call
// itself is untested. If the endpoint changed, update ENDPOINT below.

import { readFileSync, writeFileSync } from 'node:fs';

const MODEL = 'intfloat/multilingual-e5-small';
const DIMENSIONS = 384;
const ENDPOINT = `https://router.huggingface.co/hf-inference/models/${MODEL}/pipeline/feature-extraction`;
const BATCH = 16;

const args = process.argv.slice(2);
const fake = args.includes('--fake');
const outIndex = args.indexOf('--out');
const root = new URL('..', import.meta.url);
const outPath = outIndex >= 0 ? args[outIndex + 1] : new URL('db/903_bench_embeddings.sql', root);

function readCsv(path) {
  const [header, ...lines] = readFileSync(new URL(path, root), 'utf8').trim().split(/\r?\n/);
  const columns = header.split(',');
  return lines.map((line) => Object.fromEntries(columns.map((c, i) => [c, line.split(',')[i]])));
}

function normalise(vector) {
  const length = Math.hypot(...vector);
  return vector.map((x) => x / length);
}

// Deterministic pseudo-random vector from a string, only for testing the SQL.
function fakeVector(text) {
  let seed = [...text].reduce((h, ch) => (h * 31 + ch.codePointAt(0)) >>> 0, 7);
  return normalise(
    Array.from({ length: DIMENSIONS }, () => {
      seed = (seed * 1103515245 + 12345) >>> 0;
      return seed / 2 ** 32 - 0.5;
    })
  );
}

async function embed(texts) {
  if (fake) return texts.map(fakeVector);
  if (!process.env.HF_TOKEN) throw new Error('HF_TOKEN is not set. See the comment at the top of this file.');
  const vectors = [];
  for (let i = 0; i < texts.length; i += BATCH) {
    const response = await fetch(ENDPOINT, {
      method: 'POST',
      headers: { Authorization: `Bearer ${process.env.HF_TOKEN}`, 'Content-Type': 'application/json' },
      body: JSON.stringify({ inputs: texts.slice(i, i + BATCH), options: { wait_for_model: true } }),
    });
    if (!response.ok) throw new Error(`Hugging Face API ${response.status}: ${await response.text()}`);
    const batch = await response.json();
    for (const vector of batch) {
      if (vector.length !== DIMENSIONS) throw new Error(`Expected ${DIMENSIONS} numbers, got ${vector.length}`);
      vectors.push(normalise(vector));
    }
  }
  return vectors;
}

// e5 models expect these prefixes
const products = readCsv('fixtures/catalog.csv');
const queries = readCsv('fixtures/queries.csv');
const productVectors = await embed(
  products.map((p) => `passage: ${p.title} ${p.title_en} ${p.category} ${p.description}`)
);
const queryVectors = await embed(queries.map((q) => `query: ${q.query}`));

const literal = (vector) => `'[${vector.map((x) => x.toFixed(6)).join(',')}]'`;
const rows = (items, vectors) =>
  items.map((item, i) => `  ('${item.id}', ${literal(vectors[i])})`).join(',\n');

const sql = `-- 903_bench_embeddings.sql
-- Generated by scripts/embed-fixtures.mjs${fake ? ' --fake (MADE-UP VECTORS, not real embeddings)' : ` with ${MODEL}`}.
-- Do not edit by hand. Requires pgvector and 900_bench_schema.sql. Safe to run again.

create schema if not exists extensions;
create extension if not exists vector with schema extensions;

drop table if exists bench.product_embeddings;
drop table if exists bench.query_embeddings;
create table bench.product_embeddings (id text primary key, embedding extensions.vector(${DIMENSIONS}) not null);
create table bench.query_embeddings (id text primary key, embedding extensions.vector(${DIMENSIONS}) not null);

insert into bench.product_embeddings (id, embedding) values
${rows(products, productVectors)};

insert into bench.query_embeddings (id, embedding) values
${rows(queries, queryVectors)};
`;

writeFileSync(outPath, sql);
console.log(`Wrote ${outPath}: ${products.length} products, ${queries.length} queries${fake ? ' (fake vectors)' : ''}`);
