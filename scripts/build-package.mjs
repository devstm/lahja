// Builds the database.dev package in package/ from the package files in db/.
// Run: node scripts/build-package.mjs
// Then publish (needs a database.dev account): dbdev login, then dbdev publish --path package
//
// db/ stays the single source of truth. Test files (even numbers) and benchmark
// files (900 and up) are not part of the package.

import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync } from 'node:fs';

const VERSION = '0.1.0';
const PARTS = ['001_normalize.sql', '003_skeleton.sql', '005_lexicon.sql', '007_search.sql', '009_hybrid.sql'];

const root = new URL('..', import.meta.url);
const packageDir = new URL('package/', root);
mkdirSync(packageDir, { recursive: true });

// fail loudly if a new package file appears in db/ but is not listed above
const packageFiles = readdirSync(new URL('db/', root)).filter((name) => {
  const number = Number(name.slice(0, 3));
  return name.endsWith('.sql') && number < 900 && number % 2 === 1;
});
const missing = packageFiles.filter((name) => !PARTS.includes(name));
if (missing.length) throw new Error(`Add these to PARTS in build-package.mjs: ${missing.join(', ')}`);

const body = PARTS.map(
  (name) => `-- ===== ${name} =====\n\n${readFileSync(new URL(`db/${name}`, root), 'utf8').trim()}\n`
).join('\n');

const sql = `-- lahja ${VERSION}
-- Generated by scripts/build-package.mjs from db/. Do not edit by hand.

${body}
-- ===== extension only =====

-- Back up user lexicon rows only; starter rows are recreated by this script.
select pg_catalog.pg_extension_config_dump('lahja.lexicon', 'where not is_starter');
`;

const control = `default_version = '${VERSION}'
comment = 'Smart Arabic search for Postgres: spelling variants, Arabizi, dialects, typos and hybrid ranking'
relocatable = false
`;

writeFileSync(new URL(`lahja--${VERSION}.sql`, packageDir), sql);
writeFileSync(new URL('lahja.control', packageDir), control);
copyFileSync(new URL('README.md', root), new URL('README.md', packageDir));
console.log(`Built package/lahja--${VERSION}.sql from ${PARTS.length} files, plus lahja.control and README.md`);
