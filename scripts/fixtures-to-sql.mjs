// Generates db/004_bench_seed.sql from fixtures/catalog.csv and fixtures/queries.csv.
// Run: node scripts/fixtures-to-sql.mjs
// The fixtures have no quoted fields, so a plain comma split is enough.

import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);

function readCsv(path) {
  const [header, ...lines] = readFileSync(new URL(path, root), 'utf8').trim().split(/\r?\n/);
  const columns = header.split(',');
  return lines.map((line) => {
    const values = line.split(',');
    if (values.length !== columns.length) throw new Error(`${path}: wrong column count in "${line}"`);
    return Object.fromEntries(columns.map((column, i) => [column, values[i]]));
  });
}

const text = (value) => (value === '' ? 'null' : `'${value.replaceAll("'", "''")}'`);

const products = readCsv('fixtures/catalog.csv').map(
  (p) =>
    `  (${text(p.id)}, ${text(p.title)}, ${text(p.title_en)}, ${text(p.category)}, ` +
    `${text(p.brand)}, ${Number(p.price)}, ${text(p.description)})`
);

const queries = readCsv('fixtures/queries.csv').map((q) => {
  const ids = q.expected_ids ? q.expected_ids.split(';').map(text).join(', ') : '';
  return `  (${text(q.id)}, ${text(q.query)}, ${text(q.slice)}, array[${ids}]::text[])`;
});

const sql = `-- 004_bench_seed.sql
-- Generated by scripts/fixtures-to-sql.mjs from fixtures/. Do not edit by hand.
-- Requires 003_bench_schema.sql. Safe to run again.

truncate bench.products, bench.queries;

insert into bench.products (id, title, title_en, category, brand, price, description) values
${products.join(',\n')};

insert into bench.queries (id, query, slice, expected_ids) values
${queries.join(',\n')};
`;

writeFileSync(new URL('db/004_bench_seed.sql', root), sql);
console.log(`Wrote db/004_bench_seed.sql: ${products.length} products, ${queries.length} queries`);
